describe("holidaysOf", () => {
  for (const [year, expected] of Object.entries(PUBLISHED)) {
    it(`${year} 年の祝日が公表値と一致する`, () => {
      expect(Object.fromEntries(holidaysOf(Number(year)))).toEqual(expected);
    });
  }

  it("日付順に並ぶ", () => {
    const dates = [...holidaysOf(2026).keys()];
    expect(dates).toEqual([...dates].sort());
  });
});

describe("holidayName", () => {
  it("祝日なら名前、そうでなければ null を返す", () => {
    expect(holidayName("2026-11-03")).toBe("文化の日");
    expect(holidayName("2026-11-04")).toBeNull();
  });
});

describe("暦の計算", () => {
  it("曜日を 0（日曜）〜 6 で返す", () => {
    expect(weekdayOf(2026, 11, 1)).toBe(0);
    expect(weekdayOf(2026, 11, 18)).toBe(3);
  });

  it("月の日数を返す（うるう年を含む）", () => {
    expect(daysInMonth(2026, 2)).toBe(28);
    expect(daysInMonth(2028, 2)).toBe(29);
    expect(daysInMonth(2026, 11)).toBe(30);
  });
});
